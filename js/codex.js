function renderCodex() {
    const body = document.getElementById('codexBody');
    if (!body) return;
    body.innerHTML = CODEX_SECTIONS.map(sec => `
        <div class="codex-section">
            <div class="codex-section-title">${sec.title}</div>
            ${sec.lines.map(l => `<div class="codex-line">${renderGlossaryText(l)}</div>`).join('')}
        </div>`).join('');
}

function showCodex() {
    renderCodex();
    const ov = document.getElementById('codexOverlay');
    if (ov) ov.style.display = 'flex';
}

function closeCodex() {
    const ov = document.getElementById('codexOverlay');
    if (ov) ov.style.display = 'none';
}
